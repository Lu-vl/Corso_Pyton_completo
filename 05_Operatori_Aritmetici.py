# Operatori aritmetici
'''
+ somma
- sottrazione
* moltiplicazione
/ divisione
// divisione intera
% modulo (resto di una divisione)
** potenza
'''

num1 = int(input("Inserisci il primo numero 0 a 1000000: "))
num2 = int(input("Inserisci il secondo numero 0 a 1000000: "))

risult = num1 + num2
print(risult)
risult = num1 - num2
print(risult)
risult = num1 * num2
print(risult)
risult = num1 / num2
print(risult)
risult = num1 // num2
print(risult)
risult = num1 % num2
print(risult)